    /**
     * Initialize google maps widget
     *
     * @param {Object} html node
     * @return {Void}
     */
    OP3.GoogleMaps.init = function(node) {
        var $maps = $(node);

        if ($maps.length < 1)
            $maps = $('[data-op3-element-type="googlemaps"]');

        $maps.each(function() {
            var element = OP3.$(this).element();
            var $widget = $(this).find(".google-maps-widget");
            var theme = $widget.attr("data-op3-googlemaps-theme");
            var zoomControl = $widget.attr("data-op3-googlemaps-zoom-control") === "1" ? true : false;
            var streetViewControl = $widget.attr("data-op3-googlemaps-streetview-control") === "1" ? true : false;
            var fullscreenControl = $widget.attr("data-op3-googlemaps-fullscreen-control") === "1" ? true : false;
            var scrollwheel = $widget.attr("data-op3-googlemaps-scrollwheel") === "1" ? true : false;
            var zoom = parseInt($widget.attr("data-op3-googlemaps-zoom"), 10);
            var title = $widget.attr("data-op3-googlemaps-title");
            var text = $widget.attr("data-op3-googlemaps-text");
            var position = $widget.attr("data-op3-googlemaps-position").split(',');
            position = { lat: parseFloat(position[0]), lng: parseFloat(position[1]) };

            // Init map
            var map = new google.maps.Map(this.querySelector('.google-maps-widget'), {
                center: position,
                zoom: zoom,
                styles: themes[theme],
                zoomControl: zoomControl,
                streetViewControl: streetViewControl,
                fullscreenControl: fullscreenControl,
                scrollwheel: scrollwheel,
                zoom: zoom,

                // double click is used to place a pin
                disableDoubleClickZoom: true,
            });

            // Init marker
            var marker = new google.maps.Marker({
                position: position,
                map,
                draggable: true,
                title:"Drag to reposition the marker",
            });

            // Set new marker position when dragged
            marker.addListener('dragend', function(event) {
                var value = '' + event.latLng.lat() + ',' + event.latLng.lng();
                element.setOption('googlemapsPosition', value);
            });

            // Init Info Window
            title = title ? "<h2>" + title + "</h2>" : "";
            text = text ? "<p>" + text + "</p>" : "";
            var infowindow = new google.maps.InfoWindow({
                content: title + text
            });

            // Open Info Window on click
            marker.addListener("click", function() {
                if (infowindow.getContent())
                    infowindow.open(map, marker);
            });

            // Open Info Window on load
            if (infowindow.getContent())
                infowindow.open(map, marker);

            // Set marker position when the map is double-clicked.
            google.maps.event.addListener(map, "dblclick", function(event) {
                marker.setPosition(event.latLng);

                var value = '' + event.latLng.lat() + ',' + event.latLng.lng();
                element.setOption('googlemapsPosition', value);
            });

            // Globalize
            OP3.GoogleMaps.maps = OP3.GoogleMaps.maps || {};
            OP3.GoogleMaps.maps[$(this).attr("data-op3-uuid")] = {
                map: map,
                marker: marker,
                infowindow: infowindow,
            };
        });
    };

    /**
     * Update an existing map widget
     *
     * @param {Object} node
     * @param {String} prop
     * @param {String} value
     * @return {Void}
     */
    OP3.GoogleMaps.update = function(node, prop, value) {
        var $map = $(node);
        var id = $map.attr("data-op3-uuid");
        var map = OP3.GoogleMaps.maps[id].map;
        var marker = OP3.GoogleMaps.maps[id].marker;
        var infowindow = OP3.GoogleMaps.maps[id].infowindow;
        var option = prop.replace("googlemaps", "");
        option = option.charAt(0).toLowerCase() + option.slice(1);

        // Info Window
        if (option === "title" || option === "text") {
            var $widget = $map.find(".google-maps-widget");
            var title = $widget.attr("data-op3-googlemaps-title");
            var text = $widget.attr("data-op3-googlemaps-text");
            title = title ? "<h2>" + title + "</h2>" : "";
            text = text ? "<p>" + text + "</p>" : "";
            infowindow.setContent(title + text);
            return;
        }

        // Marker
        if (option === "position") {
            option = "center";
            value = value.split(',');
            value = { lat: parseFloat(value[0]), lng: parseFloat(value[1]) };
            marker.setPosition(value);
            return;
        }

        // Map options
        if (option === "streetViewControl" || option === "fullscreenControl" || option === "scrollwheel") value = value === "1" ? true : false;
        if (option === "zoom") value = parseInt(value, 10);
        if (option === "theme") {
            option = "styles";
            value = themes[value];
        }

        // Set map options
        var result = {};
        result[option] = value;
        map.setOptions(result);
    };

